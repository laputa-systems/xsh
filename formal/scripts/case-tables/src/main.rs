//! Writes `formal/Xsh/Values/CaseTables.lean` from this toolchain's own
//! `char::to_lowercase`, `char::to_uppercase`, `char::is_cased` and
//! `char::is_case_ignorable`, which `str::to_lowercase` and
//! `str::to_uppercase` use.
#![feature(titlecase, case_ignorable)]

fn mappings(map: impl Fn(char) -> Vec<u32>) -> (Vec<(u32, u32, u32, i64)>, Vec<(u32, Vec<u32>)>) {
    let mut singles = Vec::new();
    let mut multis = Vec::new();
    for code in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(code) else { continue };
        let out = map(c);
        if out == [code] {
            continue;
        }
        if out.len() == 1 { singles.push((code, out[0])) } else { multis.push((code, out)) }
    }
    let mut runs = Vec::new();
    let mut i = 0;
    while i < singles.len() {
        let (start, target) = singles[i];
        let delta = target as i64 - start as i64;
        let mut best = (1, 1);
        for stride in [1u32, 2] {
            let mut j = i;
            while j + 1 < singles.len()
                && singles[j + 1].0 == singles[j].0 + stride
                && singles[j + 1].1 as i64 - singles[j + 1].0 as i64 == delta
            {
                j += 1;
            }
            if j - i + 1 > best.0 {
                best = (j - i + 1, stride);
            }
        }
        let (count, stride) = best;
        runs.push((start, start + (count as u32 - 1) * stride, stride, delta));
        i += count;
    }
    (runs, multis)
}

fn ranges(test: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out = Vec::new();
    let mut start = None;
    for code in 0u32..=0x110000 {
        let hit = char::from_u32(code).is_some_and(&test);
        match (hit, start) {
            (true, None) => start = Some(code),
            (false, Some(first)) => {
                out.push((first, code - 1));
                start = None;
            }
            _ => {}
        }
    }
    out
}

fn main() {
    let (lower_runs, lower_multi) = mappings(|c| c.to_lowercase().map(u32::from).collect());
    let (upper_runs, upper_multi) = mappings(|c| c.to_uppercase().map(u32::from).collect());
    let runs = |runs: &[(u32, u32, u32, i64)]| {
        runs.iter().map(|(s, e, k, d)| format!("({s}, {e}, {k}, {d})")).collect::<Vec<_>>().join(",\n   ")
    };
    let multi = |multi: &[(u32, Vec<u32>)]| {
        multi
            .iter()
            .map(|(c, out)| format!("({c}, [{}])", out.iter().map(u32::to_string).collect::<Vec<_>>().join(", ")))
            .collect::<Vec<_>>()
            .join(",\n   ")
    };
    let spans = |ranges: &[(u32, u32)]| {
        ranges.iter().map(|(a, b)| format!("({a}, {b})")).collect::<Vec<_>>().join(",\n   ")
    };
    println!("namespace Xsh.Values.CaseTables\n");
    println!("/-! Generated by `formal/scripts/case-tables` from Rust's own case data; do not edit. -/\n");
    println!("/-- Lowercase runs `(first, last, stride, offset)`. -/\ndef lowerRuns : List (Nat × Nat × Nat × Int) :=\n  [{}]\n", runs(&lower_runs));
    println!("/-- Lowercase mappings to more than one character. -/\ndef lowerMulti : List (Nat × List Nat) :=\n  [{}]\n", multi(&lower_multi));
    println!("/-- Uppercase runs `(first, last, stride, offset)`. -/\ndef upperRuns : List (Nat × Nat × Nat × Int) :=\n  [{}]\n", runs(&upper_runs));
    println!("/-- Uppercase mappings to more than one character. -/\ndef upperMulti : List (Nat × List Nat) :=\n  [{}]\n", multi(&upper_multi));
    println!("/-- The `Cased` code point ranges. -/\ndef casedRanges : List (Nat × Nat) :=\n  [{}]\n", spans(&ranges(|c| c.is_cased())));
    println!("/-- The `Case_Ignorable` code point ranges. -/\ndef ignorableRanges : List (Nat × Nat) :=\n  [{}]\n", spans(&ranges(|c| c.is_case_ignorable())));
    println!("end Xsh.Values.CaseTables");
}
