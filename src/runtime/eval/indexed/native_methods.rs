use crate::modules::{RuntimeOp, signature::MethodReceiver};

// Prepared text and byte methods choose their backend spelling from the
// selected numeric operation and receiver domain, independently of source text.
pub(in crate::runtime::eval) fn nondefault_method_spelling(receiver: MethodReceiver, operation: RuntimeOp) -> Option<&'static str> {
    match (receiver, operation) {
        (MethodReceiver::Str, RuntimeOp::TextTrim) => Some("trim"),
        (MethodReceiver::Str, RuntimeOp::TextStartsWith) => Some("starts_with"),
        (MethodReceiver::Str, RuntimeOp::TextEndsWith) => Some("ends_with"),
        (MethodReceiver::Str, RuntimeOp::TextStreamLines) => Some("lines"),
        (MethodReceiver::Str, RuntimeOp::TextWords) => Some("words"),
        (MethodReceiver::Str, RuntimeOp::TextReplace) => Some("replace"),
        (MethodReceiver::Str, RuntimeOp::TextWrap) => Some("wrap"),
        (MethodReceiver::Str, RuntimeOp::TextTranslate) => Some("translate"),
        (MethodReceiver::Str, RuntimeOp::TextLower) => Some("lower"),
        (MethodReceiver::Str, RuntimeOp::TextUpper) => Some("upper"),
        (MethodReceiver::Str, RuntimeOp::TextDelete) => Some("delete"),
        (MethodReceiver::Str, RuntimeOp::TextReverse) => Some("reverse"),
        (MethodReceiver::Str, RuntimeOp::TextCountLines) => Some("count_lines"),
        (MethodReceiver::Str, RuntimeOp::TextCountWords) => Some("count_words"),
        (MethodReceiver::Str, RuntimeOp::TextCountChars) => Some("count_chars"),
        (MethodReceiver::Str, RuntimeOp::TextByteLen) => Some("byte_len"),
        (MethodReceiver::Str, RuntimeOp::TextByteAt) => Some("byte_at"),
        (MethodReceiver::Str, RuntimeOp::TextParseInt) => Some("parse_int"),
        (MethodReceiver::Str, RuntimeOp::TextParseIntDecimal) => Some("parse_int_decimal"),
        (MethodReceiver::Str, RuntimeOp::TextParseUint) => Some("parse_uint"),
        (MethodReceiver::Str, RuntimeOp::TextParseUintPositive) => Some("parse_uint_positive"),
        (MethodReceiver::Str, RuntimeOp::TextParseFloat) => Some("parse_float"),
        (MethodReceiver::Str, RuntimeOp::BytesBase64Decode) => Some("base64_decode"),
        (MethodReceiver::Str, RuntimeOp::BytesBase32Decode) => Some("base32_decode"),
        (MethodReceiver::Bytes, RuntimeOp::BytesLen) => Some("len"),
        (MethodReceiver::Bytes, RuntimeOp::BytesBase64) => Some("base64"),
        (MethodReceiver::Bytes, RuntimeOp::BytesBase32) => Some("base32"),
        (MethodReceiver::Bytes, RuntimeOp::BytesUtf8) => Some("utf8"),
        (MethodReceiver::Bytes, RuntimeOp::BytesChunks) => Some("chunks"),
        (MethodReceiver::Bytes, RuntimeOp::BytesCompare) => Some("compare"),
        (MethodReceiver::Bytes, RuntimeOp::BytesStreamLines) => Some("lines"),
        (MethodReceiver::Bytes, RuntimeOp::BytesCountLines) => Some("count_lines"),
        (MethodReceiver::Bytes, RuntimeOp::BytesTrim) => Some("trim"),
        (MethodReceiver::Bytes, RuntimeOp::BytesStartsWith) => Some("starts_with"),
        (MethodReceiver::Bytes, RuntimeOp::BytesEndsWith) => Some("ends_with"),
        (MethodReceiver::Bytes, RuntimeOp::BytesLower) => Some("lower"),
        (MethodReceiver::Bytes, RuntimeOp::BytesByteAt) => Some("byte_at"),
        (MethodReceiver::Bytes, RuntimeOp::HashMd5) => Some("md5"),
        (MethodReceiver::Bytes, RuntimeOp::HashSha1) => Some("sha1"),
        (MethodReceiver::Bytes, RuntimeOp::HashSha256) => Some("sha256"),
        (MethodReceiver::Bytes, RuntimeOp::HashSha512) => Some("sha512"),
        _ => None,
    }
}
